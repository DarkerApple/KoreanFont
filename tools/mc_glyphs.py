def bitmap(char):
    """8x8 rows of '#'/'.' for a character, or None if we do not draw it."""
    for table in (UPPER, LOWER, DIGITS, PUNCT, EXTRA):
        if char in table:
            rows = table[char].split("/")
            top = 0 if len(rows) >= 6 and char not in LOWER else 0
            return _pad(rows, char)
    if char in ACCENTED:
        base, accent = ACCENTED[char]
        rows = _pad(LOWER[base].split("/"), base)
        if accent and ACCENTS.get(accent):
            mark = ACCENTS[accent].split("/")
            out = list(rows)
            for i, m in enumerate(mark[:2]):
                out[i] = (m + "." * 8)[:8]
            return out
        return rows
    if char in BASE_ONLY:
        base = BASE_ONLY[char]
        table = UPPER if base in UPPER else LOWER
        return _pad(table[base].split("/"), base)
    return None


def _pad(rows, char):
    """Place the drawn rows in an 8x8 cell, bottom-aligned on the baseline."""
    descends = char in "gjpqy" or (len(rows) > 6)
    height = len(rows)
    if descends:
        top = 8 - height if height >= 7 else 6 - height
    else:
        top = 6 - height
    cell = ["." * 8] * 8
    for i, r in enumerate(rows):
        y = top + i
        if 0 <= y < 8:
            cell[y] = (r + "." * 8)[:8]
    return cell
